import { Labels, RunDetails } from '../schema';
import { effectiveVerdict } from './dataset';
import { Verdict } from './metrics';
import { ArticlePrediction, scoreRun } from './scoring';

const pct = (n: number | null) => (n === null ? 'n/d' : `${Math.round(n * 100)}%`);

export function renderSweep(dataset: string, result: ReturnType<typeof sweepRetrieval>, configs: string[]): string {
  const { rows, separation } = result;
  const lines = [
    '# Retrieval threshold sweep',
    '',
    `Generated by \`pnpm eval:sweep\` for dataset \`${dataset}\` from the candidates stored with each run; no model calls. Only aggregate numbers appear here.`,
    '',
    `- Pairs scored: ${separation.relevantPairs} relevant, ${separation.irrelevantPairs} irrelevant (${separation.irrelevantNeverRetrieved} of the irrelevant ones were never retrieved at the 0.60 cutoff used when the runs were made)`,
    `- How well distance alone separates them (AUC, 1 = perfect, 0.5 = chance): ${separation.auc === null ? 'n/d' : separation.auc.toFixed(3)}`,
    `- Median distance: relevant ${separation.relevantMedian?.toFixed(3) ?? 'n/d'}, irrelevant (when retrieved) ${separation.irrelevantMedian?.toFixed(3) ?? 'n/d'}`,
    '',
    '| Cutoff | LLM calls per article | Relevant pairs kept | Irrelevant pairs kept | Unrelated articles that still call the LLM | ' + configs.map(c => `Projected macro-F1 ${c}`).join(' | ') + ' |',
    '|---|---|---|---|---|' + configs.map(() => '---').join('|') + '|',
    ...rows.map(r => `| ${r.label} | ${r.pairsPerArticle.toFixed(2)} | ${pct(r.relevantRecall)} | ${pct(r.irrelevantPassRate)} | ${pct(r.falseRetrievalRate)} | ` +
      configs.map(c => r.projected[c].macroF1 === null ? 'n/d' : r.projected[c].macroF1!.toFixed(2)).join(' | ') + ' |'),
    '',
    '**How to read it.** "Projected" macro-F1 assumes each model would answer the same for the pairs that remain. That is not guaranteed: the prompt includes the closest note only when it passes the cutoff, so a cutoff chosen from this table must be confirmed with a real run before it becomes the default.',
    '',
  ];
  return lines.join('\n');
}

export interface SweepRow {
  label: string;
  /** Distance cutoff, or null for the rank-only rows. */
  threshold: number | null;
  /** Rank cutoff (closest N projects), or null for the distance-only rows. */
  rank: number | null;
  /** Projects handed to the LLM per article: this is the cost driver. */
  pairsPerArticle: number;
  /** Share of relevant (actionable or tentative) pairs that still reach the LLM. */
  relevantRecall: number | null;
  /** Share of irrelevant pairs that still reach the LLM. */
  irrelevantPassRate: number | null;
  /** Share of articles with no relevant project that still reach the LLM with at least one. */
  falseRetrievalRate: number | null;
  /** Triage quality per config if the verdicts of the kept pairs did not change. */
  projected: Record<string, { macroF1: number | null; actionableRecall: number | null; actionablePrecision: number | null }>;
}

export interface SweepInput {
  projects: string[];
  cases: Labels['cases'];
  runs: Record<string, RunDetails>;
  thresholds: number[];
  ranks: number[];
  /** Distance cutoff and rank cutoff applied together, as [threshold, rank]. */
  combos?: [number, number][];
}

const median = (values: number[]) => {
  if (values.length === 0) return null;
  const sorted = [...values].sort((a, b) => a - b);
  const mid = Math.floor(sorted.length / 2);
  return sorted.length % 2 ? sorted[mid] : (sorted[mid - 1] + sorted[mid]) / 2;
};

/**
 * Re-filters the candidates stored with each run by distance and/or rank and scores what is
 * left. Retrieval is the same for every config, so the first run supplies the candidates.
 * Triage numbers are a projection: they assume the model would answer the same for the pairs
 * that stay, which holds unless the prompt changes (the focal note appears only when it is close
 * enough), so a chosen cutoff must be confirmed with a real run.
 */
export function sweepRetrieval({ projects, cases, runs, thresholds, ranks, combos = [] }: SweepInput) {
  const names = Object.keys(runs).sort();
  const reference = runs[names[0]];

  // Only articles the owner labeled are scored
  const scored = cases.filter(c => projects.some(p => effectiveVerdict(c, p) !== null));
  const labeled = scored.map(c => ({
    article: c.article,
    verdicts: Object.fromEntries(projects.map(p => [p, effectiveVerdict(c, p) as Verdict])) as Record<string, Verdict>,
  }));

  const makeRow = (label: string, threshold: number | null, rank: number | null): SweepRow => {
    const keep = (run: RunDetails, article: string) => run.articles[article].retrieval
      .filter(r => threshold === null || r.distance < threshold)
      .slice(0, rank ?? Infinity)
      .map(r => r.project);

    let pairs = 0, relevant = 0, relevantKept = 0, irrelevant = 0, irrelevantKept = 0, negatives = 0, falseRetrievals = 0;
    for (const { article, verdicts } of labeled) {
      const kept = new Set(keep(reference, article));
      pairs += kept.size;
      for (const [project, verdict] of Object.entries(verdicts)) {
        if (verdict === 'irrelevant') { irrelevant++; if (kept.has(project)) irrelevantKept++; }
        else { relevant++; if (kept.has(project)) relevantKept++; }
      }
      if (Object.values(verdicts).every(v => v === 'irrelevant')) {
        negatives++;
        if (kept.size > 0) falseRetrievals++;
      }
    }

    const projected = Object.fromEntries(names.map(name => {
      const run = runs[name];
      const predictions: Record<string, ArticlePrediction> = {};
      for (const { article } of labeled) {
        const kept = keep(run, article);
        predictions[article] = {
          retrieved: kept,
          pairs: Object.fromEntries(kept.filter(p => run.articles[article].pairs[p]).map(p => {
            const pair = run.articles[article].pairs[p];
            return [p, { verdict: pair.verdict, targetFile: pair.action?.targetFile ?? null }];
          })),
        };
      }
      const score = scoreRun({ projects, cases: scored, predictions, k: run.k });
      const actionable = score.triage.perClass.actionable;
      return [name, { macroF1: score.triage.macroF1, actionableRecall: actionable.recall, actionablePrecision: actionable.precision }];
    }));

    return {
      label, threshold, rank,
      pairsPerArticle: labeled.length ? pairs / labeled.length : 0,
      relevantRecall: relevant ? relevantKept / relevant : null,
      irrelevantPassRate: irrelevant ? irrelevantKept / irrelevant : null,
      falseRetrievalRate: negatives ? falseRetrievals / negatives : null,
      projected,
    };
  };

  const rows = [
    ...thresholds.map(t => makeRow(`distancia < ${t.toFixed(2)}`, t, null)),
    ...ranks.map(r => makeRow(r === 1 ? 'solo el más cercano' : `los ${r} más cercanos`, null, r)),
    ...combos.map(([t, r]) => makeRow(`distancia < ${t.toFixed(2)} y los ${r} más cercanos`, t, r)),
  ];

  // How well distance alone ranks relevant pairs ahead of irrelevant ones (1 = perfectly,
  // 0.5 = no better than chance). A pair that was not retrieved counts as infinitely far.
  const distanceOf = (article: string, project: string) =>
    reference.articles[article].retrieval.find(r => r.project === project)?.distance ?? Infinity;
  const relevantDistances: number[] = [];
  const irrelevantDistances: number[] = [];
  for (const { article, verdicts } of labeled) {
    for (const [project, verdict] of Object.entries(verdicts)) {
      (verdict === 'irrelevant' ? irrelevantDistances : relevantDistances).push(distanceOf(article, project));
    }
  }
  let wins = 0;
  for (const r of relevantDistances) for (const i of irrelevantDistances) wins += r < i ? 1 : r === i ? 0.5 : 0;
  const comparisons = relevantDistances.length * irrelevantDistances.length;
  const finite = (values: number[]) => values.filter(Number.isFinite);

  return {
    rows,
    separation: {
      auc: comparisons ? wins / comparisons : null,
      relevantMedian: median(finite(relevantDistances)),
      irrelevantMedian: median(finite(irrelevantDistances)),
      relevantPairs: relevantDistances.length,
      irrelevantPairs: irrelevantDistances.length,
      irrelevantNeverRetrieved: irrelevantDistances.filter(d => !Number.isFinite(d)).length,
    },
  };
}
