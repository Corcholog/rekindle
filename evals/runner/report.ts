import * as fs from 'fs/promises';
import * as path from 'path';
import { EvalResult, ResultSchema } from '../schema';

export async function loadResults(resultsDir: string): Promise<EvalResult[]> {
  const files = (await fs.readdir(resultsDir).catch(() => [])).filter(f => f.endsWith('.json')).sort();
  const results: EvalResult[] = [];
  for (const file of files) {
    results.push(ResultSchema.parse(JSON.parse(await fs.readFile(path.join(resultsDir, file), 'utf-8'))));
  }
  return results;
}

/** The most recent run of each (dataset, config). */
export function latestPerConfig(results: EvalResult[]): EvalResult[] {
  const latest = new Map<string, EvalResult>();
  for (const r of results) {
    const key = `${r.meta.dataset}|${r.meta.config}`;
    const current = latest.get(key);
    if (!current || r.meta.startedAt > current.meta.startedAt) latest.set(key, r);
  }
  return [...latest.values()].sort((a, b) => `${a.meta.dataset}|${a.meta.config}`.localeCompare(`${b.meta.dataset}|${b.meta.config}`));
}

const pct = (n: number | null) => (n === null ? 'n/a' : `${(n * 100).toFixed(1)}%`);
const num = (n: number | null) => (n === null ? 'n/a' : String(Math.round(n)));

export function renderReport(results: EvalResult[]): string {
  const latest = latestPerConfig(results);
  const datasets = [...new Set(latest.map(r => r.meta.dataset))];
  const out: string[] = [
    '# Loom evaluation report',
    '',
    'Generated by `pnpm eval:report` from the files in `evals/results/`. Every number comes from a recorded run; nothing here is edited by hand.',
    '',
  ];

  if (latest.length === 0) {
    out.push('No runs recorded yet: **not measured**.', '');
    return out.join('\n');
  }

  for (const dataset of datasets) {
    const rows = latest.filter(r => r.meta.dataset === dataset);
    const first = rows[0].meta;
    out.push(`## Dataset \`${dataset}\``, '');
    out.push(`- Cases: ${first.cases}; labeled (article, project) pairs: ${first.labeledPairs}`);
    out.push(`- Labeled by: ${first.labeledBy ?? '**nobody yet**'}`);
    out.push(`- Embedding model: ${first.embeddingModel}; dataset manifest \`${first.datasetManifestHash.slice(0, 12)}\``);
    if (first.labeledBy === 'test-fixture') {
      out.push('', '> **Machinery check only.** These labels belong to a test fixture, not to a person judging relevance. The numbers prove the harness runs; they say nothing about quality.');
    }
    out.push('', '### Retrieval and triage', '');
    out.push('| Config | Mode | P@K | R@K | False retrieval | Macro F1 | F1 actionable | F1 tentative | F1 irrelevant | Target note |');
    out.push('|---|---|---|---|---|---|---|---|---|---|');
    for (const r of rows) {
      const f1 = (c: string) => pct(r.triage.perClass[c]?.f1 ?? null);
      out.push(`| ${r.meta.config} | ${r.meta.mode} | ${pct(r.retrieval.precisionAtK)} | ${pct(r.retrieval.recallAtK)} | ${pct(r.retrieval.falseRetrievalRate)} | ${pct(r.triage.macroF1)} | ${f1('actionable')} | ${f1('tentative')} | ${f1('irrelevant')} | ${pct(r.triage.targetNoteAccuracy)} (n=${r.triage.targetNoteCases}) |`);
    }
    out.push('', '### Reliability, latency and cost', '');
    out.push('| Config | LLM calls | Malformed outputs | Fallbacks | Failures | Rate-limit hits (waited) | p50 ms | p95 ms | Tokens in / out | Est. USD |');
    out.push('|---|---|---|---|---|---|---|---|---|---|');
    for (const r of rows) {
      out.push(`| ${r.meta.config} | ${r.reliability.llmCalls} | ${r.reliability.malformedOutputs} | ${r.reliability.fallbacks} | ${r.reliability.failures} | ${r.reliability.rateLimitHits} (${Math.round(r.reliability.rateLimitWaitMs / 1000)} s) | ${num(r.reliability.latencyMsP50)} | ${num(r.reliability.latencyMsP95)} | ${r.cost.promptTokens} / ${r.cost.completionTokens} | ${r.cost.estimatedUsd === null ? 'not measured' : r.cost.estimatedUsd.toFixed(4)} |`);
    }
    out.push('', ...rows.map(r => `- **${r.meta.config}** (commit \`${r.meta.gitSha}\`${r.meta.gitDirty ? ', dirty tree' : ''}, config \`${r.meta.configHash.slice(0, 8)}\`): ${r.cost.note}`), '');
  }

  out.push(
    '## Known weaknesses',
    '',
    '- The datasets are small: a single mislabeled or misjudged case moves the percentages visibly. Treat differences of a few points as noise.',
    '- Ground truth comes from one labeler. Where the labeler is `test-fixture`, there is no human judgement at all.',
    '- Latency depends on the time of day and provider load; cost uses list prices from `evals/configs`, and providers without a price are reported as not measured.',
    '- Suggestion quality (relevance, usefulness, actionability) is not scored automatically; it needs the owner\'s ratings and is **not measured** unless ratings are recorded.',
    '',
  );
  return out.join('\n');
}
